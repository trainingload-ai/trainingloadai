import { readdir, readFile, realpath, stat, writeFile } from 'node:fs/promises';
import { extname, resolve, relative } from 'node:path';

// Authoring sources only: generated tokens and explicit test fixtures have their own owners.
const args = process.argv.slice(2);
const reportIndex = args.indexOf('--report-json');
const reportPath = reportIndex >= 0 ? args.splice(reportIndex, 2)[1] : null;
if (reportIndex >= 0 && !reportPath) throw new Error('--report-json requires an output path');
const roots = args.map(value => resolve(value));
if (!roots.length) throw new Error('Pass one or more application source directories');
const files = [];
async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) await collect(path);
    else if (['.ts', '.tsx', '.js', '.jsx', '.css', '.swift'].includes(extname(path)) && !/\.(?:test|spec)\.[cm]?[jt]sx?$/.test(path) && !path.endsWith('.d.ts')) files.push(path);
  }
}
for (const root of roots) {
  if ((await stat(root)).isDirectory()) await collect(root);
  else files.push(root);
}
const literal = /#[\da-f]{3,8}\b|\b(?:rgba?|hsla?|oklch)\(\s*(?:\d|\.\d)|\b(?:color|backgroundColor|borderColor|fill|stroke|stopColor)\s*[:=]\s*["'](?:white|black)["']|\{\s*r:\s*\d+\s*,\s*g:\s*\d+\s*,\s*b:\s*\d+/i;
const failures = [];
const report = [];
for (const path of [...new Set(await Promise.all(files.map(path => realpath(path))))].sort()) {
  const source = await readFile(path, 'utf8');
  // This committed native copy is independently checked against the generated package output.
  if (path.endsWith('/RecordingDesignTokens.swift') && source.startsWith('// Generated by @trainingloadai/design-tokens.')) {
    report.push({ file: relative(process.cwd(), path), status: 'generated-shared-copy', issues: 0 });
    continue;
  }
  const before = failures.length;
  const lines = source.split('\n');
  for (const [index, line] of lines.entries()) {
    if (/^\s*(?:\/\/|\*|\/\*)/.test(line)) continue;
    const nativeLiteral = path.endsWith('.swift') && /(?<![\w.])(?:Color)?\.(?:red|green|blue|orange|yellow|pink|purple|cyan|mint|white|black|gray|indigo|teal|brown)\b|\b(?:red|green|blue):\s*\d/.test(line);
    if (literal.test(line) || nativeLiteral || /(?:bg|text|border|shadow)-\[[^\n]*\$\{token(?:Alpha|Colors|Palette|Visual)/.test(line)) failures.push(`${relative(process.cwd(), path)}:${index + 1}: ${line.trim()}`);
  }
  report.push({ file: relative(process.cwd(), path), status: failures.length === before ? 'passed' : 'failed', issues: failures.length - before });
}
if (reportPath) await writeFile(resolve(reportPath), JSON.stringify(report, null, 2) + '\n');
if (failures.length) {
  console.error('Fixed colors belong in @trainingloadai/design-tokens; use semantic roles, configured data/provider colors or withAlpha().');
  console.error(failures.join('\n'));
  process.exitCode = 1;
} else {
  console.log(`Color usage: ${report.filter(entry => entry.status !== 'generated-shared-copy').length} application files checked, no fixed color literals.`);
}
