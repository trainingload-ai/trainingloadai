const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dist = resolve(root, "dist");
const check = process.argv.includes("--check");

const canonical = JSON.stringify({
  schemaVersion,
  colors,
  spacing,
  radii,
  motion,
  chartColors,
  typography,
  paletteHsl,
  visualColors,
  desktopColors,
  appleSystemColors,
});
const digest = createHash("sha256").update(canonical).digest("hex");

const kebab = (value) =>
  value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const cssDeclarations = (entries, prefix = "", unit = "px") =>
  Object.entries(entries)
    .map(
      ([name, value]) =>
        `  --${prefix}${kebab(name)}: ${value}${typeof value === "number" ? unit : ""};`,
    )
    .join("\n");

const light = cssDeclarations(colors.light);
const dark = cssDeclarations(colors.dark);
const spacingCss = cssDeclarations(spacing, "tl-space-");
const radiusCss = cssDeclarations(radii, "tl-radius-");
const motionCss = cssDeclarations(motion, "motion-", "ms");
const chartCss = cssDeclarations(chartColors, "chart-");
const legacyPaletteCss = cssDeclarations(paletteHsl);
function flattenColors(value, prefix = '') {
  return Object.entries(value).flatMap(([key, entry]) => {
    const name = prefix ? `${prefix}-${kebab(key)}` : kebab(key);
    return typeof entry === 'string' ? [[name, entry]] : flattenColors(entry, name);
  });
}
const visualEntries = Object.fromEntries(flattenColors(visualColors));
const colorAliases = [
  ...Object.keys(palette).map(name => `  --color-palette-${name}: hsl(var(--${name}));`),
  ...Object.keys(visualEntries).map(name => `  --color-visual-${name}: var(--visual-${name});`),
].join('\n');
const nativePaletteCss = `/* Client-compatible primitive scales for NativeWind; generated, do not edit. */
@theme inline {
${Object.entries(palette).map(([name, value]) => `  --color-palette-${name}: ${value};`).join('\n')}
${Object.entries(visualEntries).map(([name, value]) => `  --color-visual-${name}: ${value};`).join('\n')}
${Object.entries(palette).map(([name, value]) => `  --color-${name}: ${value};`).join("\n")}
}
`;

