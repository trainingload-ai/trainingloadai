const jsExport = (name, value) =>
  `export const ${name} = Object.freeze(${JSON.stringify(value, null, 2)});\n`;
const nativeJs = [
  jsExport("colors", colors),
  jsExport("spacing", spacing),
  jsExport("radii", radii),
  jsExport("motion", motion),
  jsExport("typography", typography),
].join("\n");
const chartsJs = jsExport("chartColors", chartColors);
const metaJs = `export const designTokenMeta = Object.freeze(${JSON.stringify({ schemaVersion, digest }, null, 2)});\n`;

const nativeTypes = `export type ColorScheme = 'light' | 'dark';
export declare const colors: Readonly<Record<ColorScheme, Readonly<Record<string, string>>>>;
export declare const spacing: Readonly<Record<string, number>>;
export declare const radii: Readonly<Record<string, number>>;
export declare const motion: Readonly<Record<string, number>>;
export declare const typography: Readonly<Record<string, string>>;
`;
const chartTypes = `export declare const chartColors: Readonly<Record<string, string>>;\n`;
const metaTypes = `export type DesignTokenMeta = { schemaVersion: number; digest: string };
export declare const designTokenMeta: Readonly<DesignTokenMeta>;
`;

const outputs = new Map([
  ["web.css", webCss],
  ["native.js", nativeJs],
  ["native.d.ts", nativeTypes],
  ["charts.js", chartsJs],
  ["charts.d.ts", chartTypes],
  ["meta.js", metaJs],
  ["meta.d.ts", metaTypes],
]);

await mkdir(dist, { recursive: true });
const stale = [];
for (const [name, content] of outputs) {
  const path = resolve(dist, name);
  if (check) {
    const current = await readFile(path, "utf8").catch(() => null);
    if (current !== content) stale.push(name);
  } else {
    await writeFile(path, content);
  }
}

if (stale.length > 0) {
  console.error(`Design token outputs are stale: ${stale.join(", ")}`);
  process.exit(1);
}

console.log(
  check
    ? "Design token outputs are current."
    : `Generated design tokens (${digest}).`,
);
