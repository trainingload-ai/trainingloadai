type IntlWithSupportedValues = typeof Intl & {
  supportedValuesOf?: (key: "timeZone") => string[];
};

export function getTimezoneOffsetMinutes(
  timezone: string,
  date = new Date(),
): number | null {
  try {
    const parts = new Intl.DateTimeFormat("en-US", {
      timeZone: timezone,
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
      hourCycle: "h23",
    }).formatToParts(date);
    const value = (type: Intl.DateTimeFormatPartTypes) => {
      const raw = parts.find((part) => part.type === type)?.value;
      return raw === undefined ? Number.NaN : Number(raw);
    };
    const zonedTimestamp = Date.UTC(
      value("year"),
      value("month") - 1,
      value("day"),
      value("hour"),
      value("minute"),
      value("second"),
    );
    if (!Number.isFinite(zonedTimestamp)) return null;

    const sourceTimestamp = date.getTime() - date.getMilliseconds();
    return Math.round((zonedTimestamp - sourceTimestamp) / 60_000);
  } catch {
    return null;
  }
}

function timezoneSortRank(offsetMinutes: number | null) {
  if (offsetMinutes === null) return Number.MAX_SAFE_INTEGER;
  if (offsetMinutes === 0) return 0;
  if (offsetMinutes > 0) return offsetMinutes;
  return 2_000 + Math.abs(offsetMinutes);
}

export function sortTimezonesFromUtc(
  timezones: readonly string[],
  date = new Date(),
): string[] {
  const offsets = new Map(
    timezones.map((timezone) => [
      timezone,
      getTimezoneOffsetMinutes(timezone, date),
    ]),
  );

  return [...timezones].sort((left, right) => {
    if (left === right) return 0;
    if (left === "UTC") return -1;
    if (right === "UTC") return 1;

    const rankDiff =
      timezoneSortRank(offsets.get(left) ?? null) -
      timezoneSortRank(offsets.get(right) ?? null);
    return rankDiff || left.localeCompare(right);
  });
}

export function getTimezoneOptions(date = new Date()): string[] {
  let runtimeValues: string[] = [];
  try {
    const supportedValuesOf = (Intl as IntlWithSupportedValues).supportedValuesOf;
    if (typeof supportedValuesOf === "function") {
      runtimeValues = supportedValuesOf("timeZone").map(
        (timezone) => LEGACY_TIMEZONE_ALIASES[timezone] ?? timezone,
      );
    }
  } catch {
    runtimeValues = [];
  }

  return sortTimezonesFromUtc(
    Array.from(new Set(["UTC", ...FALLBACK_IANA_TIMEZONES, ...runtimeValues])),
    date,
  );
}

export function formatTimezoneOffsetLabel(
  timezone: string,
  date = new Date(),
): string {
  const offsetMinutes = getTimezoneOffsetMinutes(timezone, date);
  if (offsetMinutes === null) return "";
  if (offsetMinutes === 0) return "UTC+0";

  const sign = offsetMinutes > 0 ? "+" : "-";
  const absoluteMinutes = Math.abs(offsetMinutes);
  const hours = Math.floor(absoluteMinutes / 60);
  const minutes = absoluteMinutes % 60;
  return `UTC${sign}${hours}${minutes ? `:${String(minutes).padStart(2, "0")}` : ""}`;
}

export function filterTimezoneOptions(
  options: readonly string[],
  query: string,
  date = new Date(),
): string[] {
  const normalizedQuery = query.trim().toLowerCase();
  if (!normalizedQuery) return [...options];

  return options.filter((timezone) => {
    const offset = formatTimezoneOffsetLabel(timezone, date).toLowerCase();
    return [
      timezone,
      timezone.replace(/_/g, " "),
      offset,
      offset.replace(/^utc/, "gmt"),
    ]
      .join(" ")
      .toLowerCase()
      .includes(normalizedQuery);
  });
}
